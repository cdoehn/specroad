"""Relation identities and owned reservations, independent of relation endpoints.

This is not a project scan or durable reservation. The future authoring and
transaction layers must supply and recheck a complete project/history inventory.
The migration-only scheme is readable but never generated by this allocator.
"""

from dataclasses import dataclass
import secrets

from .errors import ModelError
from .identity_tokens import encode128
from .relation_values import RANDOM_SCHEME, DERIVED_SCHEME, RelationIdentity, _relation_id


def relation_identity(value):
    """Read identity only; source, target, position and labels cannot generate it."""
    if type(value) is not dict:
        raise ModelError("object_required")
    for name in ("relation_id", "id_scheme"):
        if name not in value:
            raise ModelError("missing_identity_field", pointer="/" + name)
    return RelationIdentity(value["relation_id"], value["id_scheme"])


def _ids(values, *, reject_duplicates=False):
    if isinstance(values, (str, bytes, dict)):
        raise ModelError("relation_inventory_required")
    try:
        values = tuple(values)
    except TypeError as error:
        raise ModelError("relation_inventory_required") from error
    for value in values:
        _relation_id(value)
    if reject_duplicates and len(values) != len(set(values)):
        raise ModelError("duplicate_relation_id")
    return frozenset(values)


@dataclass(frozen=True)
class RelationInventory:
    current_ids: frozenset
    archived_ids: frozenset
    reserved_ids: frozenset

    def __post_init__(self):
        for name in ("current_ids", "archived_ids", "reserved_ids"):
            object.__setattr__(self, name, _ids(getattr(self, name), reject_duplicates=name == "current_ids"))

    def contains(self, identity):
        return identity in self.current_ids or identity in self.archived_ids or identity in self.reserved_ids

    def reserve(self, identity):
        if not isinstance(identity, RelationIdentity):
            raise ModelError("relation_identity_required")
        if identity.id_scheme != RANDOM_SCHEME:
            raise ModelError("new_relation_identity_must_be_random")
        if self.contains(identity.id):
            raise ModelError("identity_already_used")
        return RelationInventory(self.current_ids, self.archived_ids, self.reserved_ids | {identity.id})


@dataclass(frozen=True)
class RelationAllocation:
    identity: RelationIdentity
    inventory: RelationInventory

    def __post_init__(self):
        if (not isinstance(self.identity, RelationIdentity)
                or not isinstance(self.inventory, RelationInventory)
                or self.identity.id_scheme != RANDOM_SCHEME
                or self.identity.id not in self.inventory.reserved_ids
                or self.identity.id in self.inventory.current_ids
                or self.identity.id in self.inventory.archived_ids):
            raise ModelError("allocation_reservation_mismatch")


def allocate_relation_identity(inventory):
    """Draw 128 fresh random bits; no endpoint, position, clock or counter input."""
    if not isinstance(inventory, RelationInventory):
        raise ModelError("relation_inventory_required")
    while True:
        try:
            random_bytes = secrets.token_bytes(16)
        except OSError as error:
            raise ModelError("entropy_unavailable") from error
        identity = RelationIdentity("REL-" + encode128(random_bytes), RANDOM_SCHEME)
        if not inventory.contains(identity.id):
            return RelationAllocation(identity, inventory.reserve(identity))


def require_relation_identity_unchanged(previous, proposed):
    """Normal edits cannot relabel an identity or switch to a migration scheme."""
    if relation_identity(previous) != relation_identity(proposed):
        raise ModelError("relation_identity_immutable")



