"""Non-normative view values and initial text/JSON presentation adapters.

The generated role is metadata, not a signature. Normative reads are restricted
by ProjectSource's path classes and trusted resource schemas, not by believing
arbitrary text labels. No import, write, rendering engine or file scan occurs.
"""

from dataclasses import dataclass
import json

from ..model.errors import ModelError
from .json_syntax import parse_json_object


def _render(raw, format):
    if format == "json":
        value = parse_json_object(raw)
        envelope = {"generated": True, "normative": False,
                    "representation_version": 1, "data": value}
        return (json.dumps(envelope, ensure_ascii=False, allow_nan=False,
                           indent=2, sort_keys=True) + "\n").encode("utf-8")
    text = raw.decode("utf-8")
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    label = "Generated by SpecRoad; non-normative view, not a model input."
    header = "<!-- " + label + " -->\n" if format in {"html", "markdown"} else label + "\n"
    return (header + text).encode("utf-8")


@dataclass(frozen=True, init=False)
class GeneratedView:
    """Immutable generated bytes; the original payload remains byte-exact.

    Only these initial adapters are offered. Other formats require their own
    later format-specific adapters; unknown formats are never mislabeled.
    """

    format: str
    payload_bytes: bytes
    content: bytes

    def __init__(self, payload_bytes: bytes, *, format: str):
        if type(payload_bytes) is not bytes:
            raise ModelError("bytes_required")
        if type(format) is not str or format not in {"json", "markdown", "html", "text"}:
            raise ModelError("unsupported_generated_format")
        try:
            payload_bytes.decode("utf-8")
            content = _render(payload_bytes, format)
        except UnicodeError as error:
            raise ModelError("invalid_utf8") from error
        except (RecursionError, TypeError) as error:
            raise ModelError("unsupported_json_representation") from error
        object.__setattr__(self, "format", format)
        object.__setattr__(self, "payload_bytes", payload_bytes)
        object.__setattr__(self, "content", content)

    @property
    def generated(self) -> bool:
        return True

    @property
    def normative(self) -> bool:
        return False
