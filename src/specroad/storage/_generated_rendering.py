"""Initial generated-view marking adapters, isolated from normative sources.

Text/HTML input is already-rendered content, not executable code or a claim of
HTML sanitization. Later renderers retain responsibility for safe rendering.
"""

from ..model._pretty_json import encode_normal_form
from .json_syntax import parse_json_object


def render_generated(raw: bytes, format: str) -> bytes:
    if format == "json":
        value = parse_json_object(raw)
        envelope = {"generated": True, "normative": False,
                    "representation_version": 1, "data": value}
        return encode_normal_form(envelope)
    text = raw.decode("utf-8")
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    label = "Generated by SpecRoad; non-normative view, not a model input."
    header = "<!-- " + label + " -->\n" if format in {"html", "markdown"} else label + "\n"
    return (header + text).encode("utf-8")
